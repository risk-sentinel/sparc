# frozen_string_literal: true

# 1.18.0-rf phase 0 — what SPARC's navigation offers, read from rendered HTML.
#
# The navigation refactor (#1286) moves every link into a new shell. Its
# promise (#1297) is that nothing reachable today becomes unreachable, and
# that needs a record of "today" taken BEFORE any navigation code changes:
# `tests/ui-smoke/nav_inventory.json`. The request spec checks the rendered
# navigation against it in both directions; the Chrome check
# (`tests/ui-smoke/test_nav_inventory.py`) reads the same file and applies the
# same normalisation, so the two cannot disagree about what an entry is.
#
# An entry is { menu, label, path }:
#   menu   where the link lives: "Header", a dropdown's name, "Account", or a
#          sidebar section ("Organizations", "Organizations > Boundary", ...)
#   label  the link's visible text, without icons, counts or status badges
#   path   the href, with record-specific parts replaced by placeholders, so
#          the inventory describes navigation rather than one database:
#            /authorization_boundaries/<slug>   -> /authorization_boundaries/:boundary
#            ?authorization_boundary_id=<id>    -> ?authorization_boundary_id=:boundary
#            /help/<slug>                       -> /help/:guide
#
# Entries that depend on data or deployment config carry `when`, which the
# Chrome check uses against a live stack: "boundary" (the viewer can see at
# least one boundary), "fido2" (SPARC_FIDO2_ENABLED), "resources" (external
# links from SPARC_RESOURCES).
module NavInventory
  extend self

  FIXTURE = Rails.root.join("tests/ui-smoke/nav_inventory.json")

  # Decoration inside a link that is not part of its name.
  DECORATION = ".badge, .sparc-dropdown-icon, .sparc-sidebar-dot, .sparc-fs-065"

  BOUNDARY = ":boundary"
  GUIDE_LABEL = "(each user guide)"

  # Each posture: how the instance is configured, who is looking (a `let` in
  # the spec), and which pages to read the navigation from. The signed-out
  # postures read the sign-in page, which is where an anonymous visitor lands,
  # and (when the library is public) a public page too.
  POSTURES = {
    "signed_out" => { auth: true, public: false, user: nil, pages: %i[login] },
    "signed_out_public_catalogs" => { auth: true, public: true, user: nil, pages: %i[login catalogs] },
    "auth_disabled" => { auth: false, public: false, user: nil, pages: %i[home] },
    "signed_in_member" => { auth: true, public: false, user: :member, pages: %i[home] },
    "signed_in_admin" => { auth: true, public: false, user: :admin, pages: %i[home] }
  }.freeze

  PAGE_PATHS = { login: :login_path, catalogs: :control_catalogs_path, home: :root_path }.freeze

  # Every link and form the header and the sidebar offer, normalised.
  def extract(html)
    doc = Nokogiri::HTML(html)
    header = doc.css("nav.navbar a[href], nav.navbar form[action]").filter_map { |el| header_entry(el) }
    sidebar = doc.css("nav.sparc-sidebar a[href]").filter_map { |el| sidebar_entry(el) }
    (header + sidebar).uniq.sort_by { |e| [ e["menu"], e["label"], e["path"] ] }
  end

  def normalize_path(href)
    return href if external?(href)

    uri = URI.parse(href)
    path = uri.path
               .sub(%r{\A/authorization_boundaries/[^/]+}, "/authorization_boundaries/#{BOUNDARY}")
               .sub(%r{\A/help/[^/]+\z}, "/help/:guide")
    return path if uri.query.blank?

    query = Rack::Utils.parse_query(uri.query)
    query[BoundaryScopedList::PARAM.to_s] = BOUNDARY if query.key?(BoundaryScopedList::PARAM.to_s)
    "#{path}?#{query.sort.map { |k, v| "#{k}=#{v}" }.join('&')}"
  end

  def condition_for(entry)
    return "resources" if external?(entry["path"])
    return "boundary" if entry["path"].include?(BOUNDARY)

    "fido2" if entry["path"] == "/webauthn_credentials"
  end

  def load
    JSON.parse(FIXTURE.read)
  end

  def write(postures)
    payload = {
      "_about" => [
        "What SPARC's navigation offers, per viewer, recorded on v1.17.5 before the",
        "1.18.0-rf navigation refactor (#1286). Generated by",
        "spec/requests/nav_inventory_spec.rb with NAV_INVENTORY_WRITE=1; read by that",
        "spec and by tests/ui-smoke/test_nav_inventory.py. See spec/support/nav_inventory.rb",
        "for what menu, label, path and when mean. Change it deliberately: an entry",
        "removed here is a link users lose."
      ],
      "postures" => postures
    }
    FIXTURE.write("#{JSON.pretty_generate(payload)}\n")
  end

  private

  def external?(href) = href.to_s.match?(%r{\Ahttps?://})

  def header_entry(el)
    href = el.name == "form" ? el["action"] : el["href"]
    return if href.blank? || href.start_with?("#")

    menu =
      if (toggle = dropdown_toggle(el))
        toggle["class"].to_s.include?("sparc-nav-user") ? "Account" : text_of(toggle)
      else
        "Header"
      end
    label = el.name == "form" ? text_of(el.at_css("button, input[type=submit]")) : link_label(el)
    label = BOUNDARY if boundary_link?(href) && menu == "Enterprise"
    build(menu, label, href)
  end

  def sidebar_entry(el)
    href = el["href"]
    if el.ancestors(".sparc-sidebar-boundary").any?
      return build("Organizations", BOUNDARY, href) if el["class"].to_s.include?("sparc-sidebar-boundary-link")

      return build("Organizations > Boundary", link_label(el), href)
    end

    section = el.ancestors(".sparc-sidebar-section").first&.at_css("button.sparc-sidebar-toggle")
    menu = section ? text_of(section) : "Sidebar"
    label = link_label(el)
    label = GUIDE_LABEL if menu == "Help & Guides" && href.start_with?("/help/") && label != "Getting Oriented"
    build(menu, label, href)
  end

  def build(menu, label, href)
    entry = { "menu" => menu, "label" => label, "path" => normalize_path(href) }
    (cond = condition_for(entry)) ? entry.merge("when" => cond) : entry
  end

  def boundary_link?(href) = href.match?(%r{\A/authorization_boundaries/[^/?]+})

  # The button that opens the dropdown an element sits in, if any.
  def dropdown_toggle(el)
    menu = el.ancestors(".dropdown-menu").first
    menu&.parent&.at_css("> .dropdown-toggle")
  end

  # Icon-only links (the help "?") are named by their aria-label.
  def link_label(el)
    text = text_of(el)
    text.presence || el["aria-label"].to_s.squish
  end

  def text_of(node)
    return "" unless node

    copy = node.dup
    copy.css(DECORATION).each(&:remove)
    text = copy.name == "input" ? copy["value"].to_s : copy.text
    # Emoji and arrow glyphs are icons, not words.
    text.gsub(/[\p{So}\p{Sm}\u{FE0F}]/, "").squish
  end
end
